import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runBlocking
import org.jetbrains.intellij.build.BuildContext
import org.jetbrains.intellij.build.BuildOptions
import org.jetbrains.intellij.build.createCommunityBuildContext
import org.jetbrains.intellij.build.productLayout.CommunityModuleSets
import org.jetbrains.intellij.build.productLayout.CoreModuleSets
import org.jetbrains.intellij.build.productLayout.buildProductContentXml
import org.jetbrains.intellij.build.productLayout.discovery.discoverModuleSets
import org.jetbrains.intellij.build.productLayout.productModules
import org.jetbrains.jps.model.java.JavaResourceRootType
import java.nio.file.Files

object GenerateWaveProductLayout {
  @JvmStatic
  fun main(args: Array<String>) {
    runBlocking(Dispatchers.Default) {
      val context = createCommunityBuildContext(BuildOptions())
      generateModuleSetDescriptors(context)
      val result = buildProductContentXml(
        spec = requireNotNull(context.productProperties.getProductContentDescriptor()),
        outputProvider = context.outputProvider,
        inlineXmlIncludes = false,
        inlineModuleSets = false,
        headerBuilder = {
          it.append("<!-- Generated by //build:generate_wave_product_layout. -->\n")
          it.append("<!-- Source: IdeaCommunityProperties.getProductContentDescriptor(). -->\n")
        },
        metadataBuilder = {},
      )
      Files.writeString(context.paths.communityHomeDir.resolve("community-resources/resources/META-INF/IdeaPlugin.xml"), result.xml)
    }
  }

  private fun generateModuleSetDescriptors(context: BuildContext) {
    val defaultDirectory = context.paths.communityHomeDir.resolve("platform/platform-resources/generated/META-INF")
    for (provider in listOf(CoreModuleSets, CommunityModuleSets)) {
      for (set in discoverModuleSets(provider).sortedBy { it.name }) {
        val directory = set.outputModule?.let { moduleName ->
          context.outputProvider.findRequiredModule(moduleName.value).sourceRoots
            .first { it.rootType == JavaResourceRootType.RESOURCE }.path.resolve("META-INF")
        } ?: defaultDirectory
        val result = buildProductContentXml(
          spec = productModules { moduleSet(set) },
          outputProvider = null,
          inlineXmlIncludes = false,
          inlineModuleSets = true,
          headerBuilder = {
            it.append("<!-- Generated by //build:generate_wave_product_layout. -->\n")
            it.append("<!-- Source: ${provider.javaClass.simpleName}, module set '${set.name}'. -->\n")
          },
          metadataBuilder = {},
        )
        Files.createDirectories(directory)
        Files.writeString(directory.resolve("intellij.moduleSets.${set.name}.xml"), result.xml)
      }
    }
  }
}
